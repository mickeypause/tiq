"""Convert the bundled Linear SVG subset to native Android vectors; no network access."""
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1] / "packages/rn-qa-overlay"
ANDROID = "http://schemas.android.com/apk/res/android"
ET.register_namespace("android", ANDROID)


def attr(name):
    return "{" + ANDROID + "}" + name


def path_data(element):
    if element.tag.rsplit("}", 1)[-1] == "path":
        return element.attrib["d"]
    assert element.tag.endswith("rect"), element.tag
    x, y, w, h, r = (float(element.get(k, "0")) for k in ["x", "y", "width", "height", "rx"])
    return (f"M{x+r},{y}H{x+w-r}A{r},{r} 0 0 1 {x+w},{y+r}V{y+h-r}"
            f"A{r},{r} 0 0 1 {x+w-r},{y+h}H{x+r}A{r},{r} 0 0 1 {x},{y+h-r}"
            f"V{y+r}A{r},{r} 0 0 1 {x+r},{y}Z")


output = ROOT / "android/src/main/res/drawable"
output.mkdir(parents=True, exist_ok=True)
entries = []
for source in sorted((ROOT / "ios/LinearIcons.xcassets").glob("*.imageset/*.svg")):
    svg = ET.parse(source).getroot()
    assert svg.attrib.get("viewBox") == "0 0 16 16", source
    vector = ET.Element("vector", {attr("width"): "16dp", attr("height"): "16dp",
                                 attr("viewportWidth"): "16", attr("viewportHeight"): "16"})
    clips = {e.attrib["id"]: e for e in svg.iter() if e.tag.endswith("clipPath")}

    def convert(element, parent):
        tag = element.tag.rsplit("}", 1)[-1]
        if tag == "defs":
            return
        if tag in ["svg", "g"]:
            if tag == "g":
                parent = ET.SubElement(parent, "group")
                clip = element.get("clip-path")
                if clip:
                    for child in clips[clip[5:-1]]:
                        ET.SubElement(parent, "clip-path", {attr("pathData"): path_data(child)})
            for child in element:
                convert(child, parent)
        else:
            assert tag in ["path", "rect"], (source, tag)
            assert element.get("fill", "currentColor") in ["currentColor", "black", "#000", "#000000"], source
            ET.SubElement(parent, "path", {attr("pathData"): path_data(element), attr("fillColor"): "#FF000000",
                attr("fillType"): "evenOdd" if element.get("fill-rule") == "evenodd" else "nonZero",
                attr("fillAlpha"): element.get("opacity", "1")})

    convert(svg, vector)
    name = "qa_linear_" + source.stem.lower()
    target = output / (name + ".xml")
    ET.indent(vector)
    ET.ElementTree(vector).write(target, encoding="unicode", xml_declaration=True)
    ET.parse(target)
    entries.append(f'  "{source.stem}" to R.drawable.{name},')

assert len(entries) == 317, len(entries)
(ROOT / "android/src/main/java/expo/modules/qaoverlay/QaLinearIconResources.kt").write_text(
    "// Generated by scripts/generate-linear-icons.py.\npackage expo.modules.qaoverlay\n\n"
    "internal val qaLinearIconResources = mapOf(\n" + "\n".join(entries) + "\n)\n")
print(f"Generated and XML-validated {len(entries)} Android icons.")
